from .flow_types import REAL
from .flow_dataclasses import *

from .evolution import *
from .models import ModelBase, ModelKPZ, ModelGenerated
from .models.model_generated import load_generated

from .evolution_two import EvolutionTwoBase, Evo2KPZ

MODELS: dict[str, type[ModelBase]] = {
    "KPZ": ModelKPZ,
}

EVO_TWO: dict[str, type[EvolutionTwoBase]] = {
    "KPZ": Evo2KPZ,
}


def create(
        model_name: str,
        model_params,
        evolution_name: str,
        evolution_params,
        evolution_two_params=None
) -> Evolution | EvolutionTwoBase:
    """
    Sets up a given evolution (evolution_name) for a
    given model (model_name).
    Parameters
    ----------
    model_name: str
        Physical model: a key of MODELS ("KPZ"), or the path of a module generated by
        FRGscalarMSR (ending in ".py", LO only, see ModelGenerated). For a generated model,
        model_params is the same tuple; its n_f must equal the module's number of functions, and it may
        continue with ModelGenerated's Integral_extrapol, regulators, fixed_etas.
    model_params: tuple
        Contains parameters accepted by the Model.
    evolution_name: str
        One grid or two grids scheme. Accepts "evo1", "evo2".
    evolution_params: tuple
        Contains parameters accepted by the Evolution.
    evolution_two_params: dict
        Contains parameters for EvolutionTwo. Needed if evolution_name is "evo2".

    Returns
    -------
    Evolution or Evolution2 class instance.
    """

    generated = str(model_name).endswith(".py")
    if not generated and model_name not in MODELS:
        raise ValueError(f"Model {model_name} not supported")
    if evolution_name not in ["evo1", "evo2"]:
        raise ValueError(f"Evolution {evolution_name} not supported")
    if generated and evolution_name == "evo2":
        raise ValueError("evo2 is not supported for generated (LO) models")

    if generated:
        module = load_generated(model_name)
        if model_params[0] != len(module.FUNCTIONS):
            raise ValueError(f"n_f = {model_params[0]}, but {model_name} has {len(module.FUNCTIONS)} "
                             f"functions {module.FUNCTIONS}")
        model = ModelGenerated(module, *model_params[1:])
    else:
        model = MODELS[model_name](*model_params)
    evo = Evolution(model, *evolution_params)  # IC, ds, path_save)

    if evolution_name == 'evo1':
        return evo
    elif evolution_name == 'evo2':
        evo2_class = EVO_TWO[model_name]
        evo2 = evo2_class(evo, **evolution_two_params)
        return evo2
    else:
        raise ValueError(f"Evolution {evolution_name} not supported")
