def repo_root():
    r = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else os.getcwd()


def load_config(root):
    path = os.path.join(root, "docs", "docgen.toml")
    cfg = {}
    if os.path.exists(path):
        with open(path, "rb") as f:
            cfg = tomllib.load(f)
    cfg.setdefault("reference", {}).setdefault("out", "docs/reference")
    cfg.setdefault("site", {}).setdefault("title", os.path.basename(root))
    return cfg


def expand(root, patterns):
    seen, out = set(), []
    for pat in patterns:
        for p in sorted(glob.glob(os.path.join(root, pat), recursive=True)):
            rel = os.path.relpath(p, root)
            if os.path.isfile(p) and rel not in seen:
                seen.add(rel)
                out.append(rel)
    return out


def read(root, rel):
    with open(os.path.join(root, rel), encoding="utf-8") as f:
        return f.read()


# ---------------------------------------------------------------- Markdown helpers

def gh_slug(text):
    """GitHub heading anchor of a Markdown heading text."""
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    t = t.strip().lower()
    t = re.sub(r"[^\w\- ]", "", t)
    return t.replace(" ", "-")


def strip_fences(md):
    """The Markdown text with fenced code blocks removed."""
    return re.sub(r"^(```|~~~).*?^\1[^\n]*$", "", md, flags=re.S | re.M)


def strip_code(md):
    """The Markdown text with fenced blocks and inline code removed (for link scans)."""
    return re.sub(r"`+[^`\n]*`+", "", strip_fences(md))


def headings(md):
    return [m.group(2) for m in re.finditer(r"^(#{1,6})\s+(.+?)\s*#*\s*$", strip_fences(md), re.M)]


def esc_md(text):
    """Escape plain text so Markdown shows it literally."""
    text = text.replace("\\", "\\\\")
    for c in "`*_[]|$":
        text = text.replace(c, "\\" + c)
    text = text.replace("<", "&lt;")
    return re.sub(r"^(\s*)#", r"\1\\#", text, flags=re.M)


def reflow(text):
    """Join hard-wrapped lines; keep blank-line paragraph breaks."""
    paras = re.split(r"\n\s*\n", text.strip())
    return "\n\n".join(" ".join(l.strip() for l in p.splitlines()) for p in paras)


def comment_block_md(lines):
    """Comment lines as Markdown: prose paragraphs reflowed; from the first column-aligned line on, a code block."""
    out = []
    for para in re.split(r"\n\s*\n", "\n".join(lines).strip()):
        rows = para.splitlines()
        k = next((i for i, l in enumerate(rows) if re.search(r"\S {2,}\S", l)), None)
        prose, table = (rows, []) if k is None else (rows[:k], rows[k:])
        if prose:
            out.append(" ".join(l.strip() for l in prose))
        if table:
            out.append("```\n" + "\n".join(table) + "\n```")
    return "\n\n".join(out)


def first_sentence(text, limit=160):
    text = " ".join(text.split())
    m = re.search(r"(?<=[.!?])\s", text)
    s = text[: m.start()] if m else text
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


