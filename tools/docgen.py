# Each returns (intro, [entries]); an entry is {name, sig, doc, internal, doc_is_md}.

WL_NAMED = {"CapitalDelta": "Δ", "Delta": "δ", "Gamma": "γ", "CapitalGamma": "Γ", "Lambda": "λ", "Mu": "μ",
            "Nu": "ν", "Omega": "ω", "Phi": "φ", "Psi": "ψ", "Partial": "∂", "Epsilon": "ε", "Eta": "η",
            "Rule": "→", "Infinity": "∞", "Element": "∈", "Sum": "∑", "Integral": "∫", "Rho": "ρ", "Sigma": "σ",
            "Tau": "τ", "Theta": "θ", "Chi": "χ", "Alpha": "α", "Beta": "β", "Kappa": "κ", "Xi": "ξ", "Zeta": "ζ"}


def wl_string(src, i):
    """Parse a Wolfram string literal whose opening quote is at src[i]; return (value, end index)."""
    out, j = [], i + 1
    while j < len(src):
        c = src[j]
        if c == '"':
            return "".join(out), j + 1
        if c == "\\" and j + 1 < len(src):
            n = src[j + 1]
            if n == "\n":
                j += 2
                continue
            if n == "[":
                k = src.find("]", j)
                name = src[j + 2:k]
                out.append(WL_NAMED.get(name, src[j:k + 1]))
                j = k + 1
                continue
            out.append({'"': '"', "\\": "\\", "n": "\n", "t": "\t"}.get(n, "\\" + n))
            j += 2
            continue
        out.append(c)
        j += 1
    raise ValueError("unterminated string")


def extract_wl(src):
    intro = ""
    for m in re.finditer(r"\(\*(.*?)\*\)", src, re.S):
        body = m.group(1).strip()
        if not body.startswith("::"):
            intro = re.sub(r"^\S+\.wl\s+-+\s+", "", body)
            break
    ctx_marks = [(m.start(), m.group(1)) for m in re.finditer(r'BeginPackage\["([^"]*)"', src)]
    entries = []
    name_pat = r"(?:[A-Za-z$]|\\\[[A-Za-z]+\])(?:[\w$`]|\\\[[A-Za-z]+\])*"
    for m in re.finditer(r'^[ \t]*(' + name_pat + r')::usage\s*=\s*"', src, re.M):
        doc, _ = wl_string(src, m.end() - 1)
        name = re.sub(r"\\\[([A-Za-z]+)\]", lambda n: WL_NAMED.get(n.group(1), n.group(0)), m.group(1))
        ctx = ""
        for pos, c in ctx_marks:
            if pos < m.start():
                ctx = c
        entries.append({"name": name, "doc": doc, "internal": "Internal" in ctx or "Private" in ctx,
                        "doc_is_md": False, "sig": None})
    return reflow(intro), entries


NUMPY_LISTS = {"parameters", "attributes", "returns", "yields", "raises", "other parameters", "keys"}


def _indent(line):
    return len(line) - len(line.lstrip())


def _deflist(lines, depth):
    """NumPy definition list ('name : type' + deeper description lines) as Markdown bullets."""
    lines = [l for l in lines if l.strip()]
    if not lines:
        return []
    base = min(_indent(l) for l in lines)
    items = []
    for l in lines:
        if _indent(l) == base or not items:
            items.append([l.strip(), []])
        else:
            items[-1][1].append(l)
    out = []
    for head, body in items:
        name, sep, typ = head.partition(":")
        if sep and re.fullmatch(r"[\w*][\w*, .]*", name.strip()):
            head = f"`{name.strip()}`" + (f" ({typ.strip()})" if typ.strip() else "")
        body = [l for l in body if l.strip()]
        nested = False
        if body:
            b0 = min(_indent(l) for l in body)
            heads = [i for i, l in enumerate(body) if _indent(l) == b0 and re.match(r"\s*[\w*][\w*, .]*\s*:", l)]
            nested = len(heads) >= 1 and any(_indent(l) > b0 for l in body) and heads[0] > 0
        if nested:
            k = heads[0]
            text = " ".join(l.strip() for l in body[:k])
            out.append("  " * depth + f"- {head}" + (f": {text}" if text else ""))
            out += _deflist(body[k:], depth + 1)
        else:
            text = " ".join(l.strip() for l in body)
            out.append("  " * depth + f"- {head}" + (f": {text}" if text else ""))
    return out


def numpy_to_md(doc):
    """A NumPy-style docstring as Markdown: underlined section titles become headings, parameter lists become bullets."""
    lines = doc.splitlines()
    if not any(re.fullmatch(r"\s*-{3,}\s*", l) for l in lines):
        return doc
    out, i, section = [], 0, None
    while i < len(lines):
        l = lines[i]
        if i + 1 < len(lines) and l.strip() and re.fullmatch(r"\s*-{3,}\s*", lines[i + 1]):
            section = l.strip().lower()
            out += ["", f"#### {l.strip()}", ""]
            i += 2
            block = []
            while i < len(lines) and not (i + 1 < len(lines) and lines[i].strip()
                                          and re.fullmatch(r"\s*-{3,}\s*", lines[i + 1])):
                block.append(lines[i])
                i += 1
            if section in NUMPY_LISTS:
                out += _deflist(block, 0)
            else:
                out += [b.strip() for b in block]
            continue
        out.append(l.strip())
        i += 1
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def extract_py(src):
    tree = ast.parse(src)
    entries = []

    def add(node, prefix=""):
        doc = ast.get_docstring(node)
        sig = None
        if isinstance(node, ast.ClassDef):
            init = next((b for b in node.body if isinstance(b, ast.FunctionDef) and b.name == "__init__"), None)
            if init:
                args = ast.unparse(init.args)
                sig = f"{node.name}({re.sub(r'^self(, )?', '', args)})"
                if ast.get_docstring(init):
                    doc = (doc + "\n\n" if doc else "") + ast.get_docstring(init)
        if node.name.startswith("_") or not doc:
            return
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            sig = f"{prefix}{node.name}({ast.unparse(node.args)})"
        entries.append({"name": prefix + node.name, "doc": numpy_to_md(doc), "internal": False, "doc_is_md": True,
                        "sig": sig})
        if isinstance(node, ast.ClassDef):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    add(sub, node.name + ".")

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            add(node)
    return numpy_to_md(ast.get_docstring(tree) or ""), entries


def extract_jl(src):
    entries = []
    pat = r'"""(.*?)"""\s*\n\s*(?:(?:function|macro|const|(?:mutable\s+)?struct|abstract\s+type)\s+)?([A-Za-z_@][\w!.]*)'
    for m in re.finditer(pat, src, re.S):
        doc = re.sub(r"^\n|\n\s*$", "", m.group(1))
        lines = doc.splitlines()
        ind = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
        lines = [l[ind:] for l in lines]
        sig = []
        while lines and (lines[0].startswith("    ") or (sig and not lines[0].strip())):
            sig.append(lines.pop(0).strip())
        sig = [l for l in sig if l]
        entries.append({"name": m.group(2), "doc": "\n".join(lines), "internal": False, "doc_is_md": True,
                        "sig": "\n".join(sig) or None})
    head = []
    for line in src.splitlines():
        if line.startswith("#") and not line.startswith("#="):
            head.append(re.sub(r"^#+ ?", "", line).rstrip())
        elif line.strip() or head:
            break
    return comment_block_md(head), entries


EXTRACTORS = {".wl": extract_wl, ".m": extract_wl, ".py": extract_py, ".jl": extract_jl}


