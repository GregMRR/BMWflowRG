def wl_to_md(text):
    """Plain usage text as Markdown: every Name[...] expression becomes a code span, the rest is escaped."""
    out, i = [], 0
    for m in re.finditer(r"(?<![\w$`])[A-Za-z$\u0370-\u03ff][\w$`]*\[", text):
        if m.start() < i:
            continue
        depth, j = 0, m.end() - 1
        while j < len(text):
            depth += {"[": 1, "]": -1}.get(text[j], 0)
            if depth == 0 and text[j + 1: j + 2] != "[":
                break
            j += 1
        if depth:
            continue
        code = text[m.start(): j + 1]
        fence = "``" if "`" in code else "`"
        pad = " " if fence == "``" else ""
        out += [esc_md(text[i: m.start()]), f"{fence}{pad}{code}{pad}{fence}"]
        i = j + 1
    out.append(esc_md(text[i:]))
    return "".join(out)


def demote_headings(md):
    """Turn headings of a docstring into level-4 headings, outside code fences."""
    out, fence = [], None
    for line in md.splitlines():
        m = re.match(r"^\s*(```|~~~)", line)
        if m:
            fence = None if fence == m.group(1) else (fence or m.group(1))
        elif not fence:
            line = re.sub(r"^#{1,6}\s+", "#### ", line)
        out.append(line)
    return "\n".join(out)


def resolve_refs(md, page, symbols):
    """Documenter cross-references [text](@ref) or [text](@ref name): link to the symbol's reference entry."""
    def sub(m):
        name = (m.group(2) or m.group(1)).strip().strip("`")
        if name not in symbols:
            return m.group(1)
        target = symbols[name]
        target = "" if target == page else target + ".md"
        return f"[{m.group(1)}]({target}#{gh_slug(f'`{name}`')})"
    return re.sub(r"\[([^\]]+)\]\(@ref(?:\s+([^)]+))?\)", sub, md)


def render_entry(e):
    lines = [f"### `{e['name']}`", ""]
    if e["sig"]:
        lines += ["```", e["sig"], "```", ""]
    if e["doc_is_md"]:
        lines.append(demote_headings(e["doc"].strip()))
    else:
        lines.append(wl_to_md(e["doc"]))
    return "\n".join(lines) + "\n"


def notes_anchor(root, notes, rel):
    if not notes or not os.path.exists(os.path.join(root, notes)):
        return None
    for h in headings(read(root, notes)):
        if rel in h.replace("`", ""):
            return gh_slug(h)
    return None


def build_reference(root, cfg):
    """Return {relative path: content} of every reference page."""
    rc = cfg["reference"]
    out = rc["out"]
    sources = expand(root, rc.get("sources", []))
    pages, index_rows, symbol_rows = {}, [], []
    extracted, symbols = [], {}
    for rel in sources:
        ext = os.path.splitext(rel)[1]
        if ext not in EXTRACTORS:
            print(f"docgen: no extractor for {rel}", file=sys.stderr)
            continue
        intro, entries = EXTRACTORS[ext](read(root, rel))
        name = os.path.splitext(os.path.basename(rel))[0]
        extracted.append((rel, ext, name, intro, entries))
        for e in entries:
            symbols.setdefault(e["name"], name)
    for rel, ext, name, intro, entries in extracted:
        for e in entries:
            if e["doc_is_md"]:
                e["doc"] = resolve_refs(e["doc"], name, symbols)
        page = f"{out}/{name}.md"
        up = os.path.relpath(root, os.path.join(root, out))
        src_link = f"[`{rel}`]({up}/{rel})"
        head = [f"{GENERATED} from {rel}: edit the doc comments there, then run `python3 tools/docgen.py reference`. -->",
                f"# {name}", ""]
        meta = f"Source: {src_link}"
        anchor = notes_anchor(root, rc.get("notes"), rel)
        if anchor:
            meta += f" · Design notes: [{os.path.basename(rc['notes'])}]({os.path.relpath(rc['notes'], out)}#{anchor})"
        head += [meta, ""]
        if intro:
            head += [intro if ext not in (".wl", ".m") else esc_md(intro), ""]
        public = [e for e in entries if not e["internal"]]
        internal = [e for e in entries if e["internal"]]
        body = []
        if public:
            body += ["## Symbols", ""] + [render_entry(e) for e in public]
        if internal:
            body += ["## Internal symbols", "", "Shared between modules; not on the user's context path.", ""]
            body += [render_entry(e) for e in internal]
        if not entries:
            body += ["No documented symbols.", ""]
        pages[page] = "\n".join(head + body).rstrip() + "\n"
        summary = first_sentence(intro) if intro else ""
        summary = esc_md(summary) if ext in (".wl", ".m") else summary.replace("|", "\\|")
        index_rows.append(f"| [{name}]({name}.md) | {summary} | {len(public)} |")
        for e in public:
            summary = first_sentence(e["doc"]) if e["doc_is_md"] else wl_to_md(first_sentence(e["doc"]))
            summary = summary.replace("\n", " ").replace("|", "\\|")
            anchor = gh_slug(f"`{e['name']}`")
            symbol_rows.append(f"| [`{e['name']}`]({name}.md#{anchor}) | {name} | {summary} |")
    index = [f"{GENERATED}: edit the doc comments in the source files, then run `python3 tools/docgen.py reference`. -->",
             "# API reference", "",
             "Generated from the doc comments in the source files. One page per file, in load order.", "",
             "| Page | Contents | Public symbols |", "|---|---|---|", *index_rows, "",
             "## All public symbols", "", "| Symbol | Page | Summary |", "|---|---|---|", *symbol_rows]
    pages[f"{out}/README.md"] = "\n".join(index) + "\n"
    return pages


def cmd_reference(root, cfg):
    pages = build_reference(root, cfg)
    out = os.path.join(root, cfg["reference"]["out"])
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(out):
        p = os.path.join(out, f)
        if f.endswith(".md") and os.path.relpath(p, root) not in pages:
            with open(p, encoding="utf-8") as fh:
                if fh.readline().startswith(GENERATED):
                    os.remove(p)
    for rel, text in pages.items():
        with open(os.path.join(root, rel), "w", encoding="utf-8") as f:
            f.write(text)
    print(f"docgen: wrote {len(pages)} pages to {cfg['reference']['out']}/")


# ---------------------------------------------------------------- check

def site_pages(root, cfg):
    pats = ["README.md", "docs/**/*.md"] + cfg["site"].get("extra", [])
    return expand(root, pats)


def check_links(root, files):
    errors, warnings = [], []
    anchors_cache = {}
    for rel in files:
        text = strip_code(read(root, rel))
        for m in re.finditer(r"(?<!\\)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", text):
            href = m.group(1)
            if re.match(r"^[a-z][a-z0-9+.-]*:", href):
                continue
            path, _, anchor = href.partition("#")
            line = text.count("\n", 0, m.start()) + 1
            target = rel if not path else os.path.normpath(os.path.join(os.path.dirname(rel), path))
            if path.startswith("/"):
                target = path.lstrip("/")
            if not os.path.exists(os.path.join(root, target)):
                errors.append(f"{rel}:{line}: broken link {href}")
                continue
            if anchor and target.endswith(".md"):
                if target not in anchors_cache:
                    anchors_cache[target] = {gh_slug(h) for h in headings(read(root, target))}
                if anchor not in anchors_cache[target]:
                    warnings.append(f"{rel}:{line}: no heading #{anchor} in {target}")
    return errors, warnings


def cmd_check(root, cfg):
    bad = False
    if cfg["reference"].get("sources"):
        for rel, text in build_reference(root, cfg).items():
            p = os.path.join(root, rel)
            if not os.path.exists(p) or read(root, rel) != text:
                print(f"docgen: stale {rel} (run `python3 tools/docgen.py reference`)")
                bad = True
    errors, warnings = check_links(root, site_pages(root, cfg))
    for w in warnings:
        print("warning: " + w)
    for e in errors:
        print("error: " + e)
    if errors or bad:
        sys.exit(1)
    print("docgen: reference up to date, links resolve")


